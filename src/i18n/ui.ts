export type Lang = keyof typeof ui;

/** The page's language, from its URL (Polish pages live under /pl/). */
export function langOf(astro: { url: URL }): Lang {
	const base = import.meta.env.BASE_URL.replace(/\/$/, '');
	const path = astro.url.pathname.slice(base.length);
	return /^\/pl(\/|$)/.test(path) ? 'pl' : 'en';
}

export function t(astro: { url: URL }) {
	return ui[langOf(astro)];
}

/** Fill {name} placeholders. */
export function fill(text: string, vars: Record<string, string | number>) {
	return Object.entries(vars).reduce((s, [k, v]) => s.split(`{${k}}`).join(String(v)), text);
}
